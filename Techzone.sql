-- Actualización automática de stock al registrar movimientos de inventario
CREATE OR REPLACE FUNCTION fn_actualizar_stock() RETURNS trigger AS $$
DECLARE
    v_efecto SMALLINT;
BEGIN
    SELECT td.efecto_en_inventario INTO v_efecto
    FROM documento d
    JOIN tipo_documento td ON td.id_tipo_documento = d.id_tipo_documento
    WHERE d.id_documento = NEW.id_documento;

    UPDATE producto
    SET stock_actual = stock_actual + (v_efecto * NEW.cantidad)
    WHERE id_producto = NEW.id_producto;

    -- Si el stock quedó igual o por debajo del mínimo y no hay alerta abierta, registrar alerta
    INSERT INTO alerta_stock (id_producto, stock_detectado, stock_minimo_momento)
    SELECT id_producto, stock_actual, stock_minimo
    FROM producto
    WHERE id_producto = NEW.id_producto
      AND stock_actual <= stock_minimo
      AND NOT EXISTS (
          SELECT 1 FROM alerta_stock a
          WHERE a.id_producto = producto.id_producto AND a.atendida = FALSE
      );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_movimiento_stock
AFTER INSERT ON movimiento_inventario
FOR EACH ROW EXECUTE FUNCTION fn_actualizar_stock();

