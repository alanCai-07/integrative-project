CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ============================================================================
-- 2. TABLAS CATÁLOGO Y CONFIGURACIÓN
-- ============================================================================

CREATE TABLE parametro (
    clave VARCHAR(50) PRIMARY KEY,
    valor NUMERIC(10, 2) NOT NULL,
    descripcion VARCHAR(255)
);

CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE metodo_pago (
    id_metodo_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tipo_documento (
    id_tipo_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(100) NOT NULL UNIQUE,
    efecto_en_inventario SMALLINT NOT NULL CHECK (efecto_en_inventario IN (1, -1))
);

CREATE TABLE cargo (
    id_cargo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- ============================================================================
-- 3. PERSONAS Y ROLES (Garantía de perfil único mediante FK compuesta)
-- ============================================================================

CREATE TABLE persona (
    id_persona INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CLIENTE', 'EMPLEADO', 'PROVEEDOR')),
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    telefono VARCHAR(30),
    email VARCHAR(120) UNIQUE,
    direccion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    -- Restricción: Todo empleado debe tener correo para iniciar sesión (RF-10)
    CONSTRAINT ck_email_empleado CHECK (tipo <> 'EMPLEADO' OR email IS NOT NULL),
    -- Llave única compuesta para validar coherencia de tipo en tablas hijas
    CONSTRAINT uq_persona_tipo UNIQUE (id_persona, tipo)
);

CREATE TABLE cliente (
    id_persona INTEGER PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL DEFAULT 'CLIENTE' CHECK (tipo = 'CLIENTE'),
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,
    -- VARCHAR(60) para hashes BCrypt; admite NULL si el cliente no tiene cuenta web/app
    contrasena_hash VARCHAR(60),
    CONSTRAINT fk_cliente_persona_tipo FOREIGN KEY (id_persona, tipo)
        REFERENCES persona(id_persona, tipo) ON DELETE RESTRICT
);

CREATE TABLE empleado (
    id_persona INTEGER PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL DEFAULT 'EMPLEADO' CHECK (tipo = 'EMPLEADO'),
    id_cargo INTEGER NOT NULL REFERENCES cargo(id_cargo) ON DELETE RESTRICT,
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
    contrasena_hash VARCHAR(60) NOT NULL,
    -- Nota: Se eliminó 'salario' en cumplimiento de Ley 1581 de 2012 (minimización de datos)
    CONSTRAINT fk_empleado_persona_tipo FOREIGN KEY (id_persona, tipo)
        REFERENCES persona(id_persona, tipo) ON DELETE RESTRICT
);

CREATE TABLE proveedor (
    id_persona INTEGER PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL DEFAULT 'PROVEEDOR' CHECK (tipo = 'PROVEEDOR'),
    nombre_empresa VARCHAR(150) NOT NULL,
    nit VARCHAR(30) UNIQUE,
    CONSTRAINT fk_proveedor_persona_tipo FOREIGN KEY (id_persona, tipo)
        REFERENCES persona(id_persona, tipo) ON DELETE RESTRICT
);

-- ============================================================================
-- 4. PRODUCTOS E INVENTARIO
-- ============================================================================

CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL REFERENCES categoria(id_categoria) ON DELETE RESTRICT,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio_compra NUMERIC(12, 2) NOT NULL,
    precio_venta NUMERIC(12, 2) NOT NULL,
    stock_actual INTEGER NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    imagen_url VARCHAR(255) NOT NULL DEFAULT 'assets/img/default.png',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_producto_precios CHECK (precio_compra > 0 AND precio_venta >= precio_compra)
);

CREATE TABLE documento (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_documento INTEGER NOT NULL REFERENCES tipo_documento(id_tipo_documento) ON DELETE RESTRICT,
    numero_comprobante INTEGER NOT NULL,
    -- id_persona es nullable para permitir ajustes/bajas internas sin cliente ni proveedor
    id_persona INTEGER REFERENCES persona(id_persona) ON DELETE RESTRICT,
    id_empleado INTEGER REFERENCES empleado(id_persona) ON DELETE SET NULL,
    id_metodo_pago INTEGER REFERENCES metodo_pago(id_metodo_pago) ON DELETE RESTRICT,
    fecha_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_documento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    numero_doc_externo VARCHAR(60),
    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    descuento NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (descuento >= 0 AND descuento <= subtotal),
    iva NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
    total NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'COMPLETADA'
        CHECK (estado IN ('PENDIENTE', 'COMPLETADA', 'ANULADA')),
    observaciones TEXT,
    -- Numeración consecutiva independiente por tipo de documento
    CONSTRAINT uq_tipo_numero_comprobante UNIQUE (id_tipo_documento, numero_comprobante)
);

CREATE TABLE movimiento_inventario (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento INTEGER NOT NULL REFERENCES documento(id_documento) ON DELETE RESTRICT,
    id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    -- Empleado que ejecuta físicamente el movimiento (puede diferir del cajero del documento)
    id_empleado INTEGER REFERENCES empleado(id_persona) ON DELETE SET NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    costo_unitario NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (costo_unitario >= 0),
    precio_unitario NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (precio_unitario >= 0),
    subtotal_linea NUMERIC(14, 2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    fecha_movimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- 5. COTIZACIONES, CARRITO Y ALERTAS
-- ============================================================================

CREATE TABLE cotizacion (
    id_cotizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_persona) ON DELETE RESTRICT,
    id_empleado INTEGER REFERENCES empleado(id_persona) ON DELETE SET NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vigencia_hasta DATE NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    iva NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
    total NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'VIGENTE'
        CHECK (estado IN ('VIGENTE', 'ACEPTADA', 'VENCIDA', 'RECHAZADA'))
);

CREATE TABLE detalle_cotizacion (
    id_detalle_cotizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion INTEGER NOT NULL REFERENCES cotizacion(id_cotizacion) ON DELETE CASCADE,
    id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    CONSTRAINT uq_cotizacion_producto UNIQUE (id_cotizacion, id_producto)
);

CREATE TABLE carrito (
    id_carrito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_persona) ON DELETE RESTRICT,
    id_documento INTEGER REFERENCES documento(id_documento) ON DELETE SET NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTO'
        CHECK (estado IN ('ABIERTO', 'CONVERTIDO', 'ABANDONADO')),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_carrito (
    id_item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrito INTEGER NOT NULL REFERENCES carrito(id_carrito) ON DELETE CASCADE,
    id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    CONSTRAINT uq_carrito_producto UNIQUE (id_carrito, id_producto)
);

CREATE TABLE alerta_stock (
    id_alerta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE CASCADE,
    stock_detectado INTEGER NOT NULL,
    stock_minimo_momento INTEGER NOT NULL,
    fecha_generacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_atencion TIMESTAMP,
    atendida BOOLEAN NOT NULL DEFAULT FALSE
);

